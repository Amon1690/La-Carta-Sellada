function buildRoleCatalog(
  role: TravelRole,
  settings: EventSetting[],
  seeds: EventSeed[]
): TravelEventDefinition[] {
  return seeds.flatMap((seed) =>
    settings.map((setting) => ({
      id: `${role}-catalog-${seed.id}-${setting.id}`,
      role,
      title: `${seed.title}: ${setting.label}`,
      polarity: seed.polarity,
      skill: seed.skill,
      dc: Math.min(18, seed.dc + (setting.dcModifier ?? 0)),
      environments: setting.environments,
      story: seed.story(setting),
      success: seed.success(setting),
      failure: seed.failure(setting),
      effect: seed.effect,
      encounterTrigger: seed.encounterTrigger,
      encounterChance: seed.encounterTrigger ? 1 : undefined,
      campaignHook: seed.campaignHook?.(setting),
      weight: seed.weight ?? 3,
    }))
  );
}

