export function encounterTier(
  encounter: GenericEncounter,
  level: number
): GenericEncounterTier {
  const safeLevel = Math.max(1, Math.min(20, Math.round(level)));
  return encounter.tiers
    .filter((tier) => tier.minLevel <= safeLevel)
    .at(-1) ?? encounter.tiers[0];
}

export function scaledEncounterMonsters(
  encounter: GenericEncounter,
  level: number,
  partySize: number
): EncounterMonster[] {
  const sizeFactor = Math.max(0.5, Math.min(2, Math.round(partySize) / 4));
  return encounterTier(encounter, level).monsters.map((monster) => ({
    ...monster,
    count: Math.max(1, Math.round(monster.count * sizeFactor)),
  }));
}
